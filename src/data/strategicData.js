export const translateStrategicTerm = (value, language = 'en') => {
  if (language !== 'ar' || value === null || value === undefined) return value;
  if (Array.isArray(value)) return value.map((item) => translateStrategicTerm(item, language)).join('، ');
  return strategicArabicTerms[value] || value;
};

export const localizeStrategicField = (item, key, language = 'en') => {
  if (!item) return '';
  const value = language === 'ar' ? item[`${key}Ar`] || item[key] : item[key];
  return translateStrategicTerm(value, language);
};

